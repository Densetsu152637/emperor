class Chat(Protocol):
    def chat(
        self,
        messages: list[dict],
        *,
        tools: list[dict] | None = ...,
        temperature: float = ...,
        seed: int | None = ...,
        max_tokens: int = ...,
        tool_choice: str | None = ...,
    ) -> dict: ...


@dataclass
class GenerationConfig:
    max_turns: int = 14
    temperature: float = 0.7
    max_tokens: int = 4096
    teacher_model: str = TEACHER_MODEL
    host: str = "local llama.cpp"  # where the teacher ran, recorded with every sample
    licence: str = LICENCE  # the terms the teacher's outputs are used under
    # Recorded with every sample and reject: pipeline commit, config hash, model ids, guidance
    # version and pilot number (hosted runs).
    provenance: dict = field(default_factory=dict)
    retries: int = 2  # extra tries (new seed) when a trace fails the schema check
    # Failures not worth paying for again: in hosted pilots 1-3 a too_long trace came back
    # too_long on 30 of 33 extra tries (the task, not the draw, is long), so the extra tries
    # cost about eleven traces per sample they rescued.
    no_retry_reasons: frozenset[str] = frozenset({"too_long"})
    force_first_tool: bool = True  # tool_choice "required" on the first turn
    direct_classes: frozenset[str] = field(default_factory=lambda: DIRECT_CLASSES)
    attempt: int = 0  # which retry round this run belongs to (0 is the first pass)
    # A thinking student trains on the teacher's reasoning: a first turn without it rejects the
    # trace (`no_reasoning`, regenerated by the retry rounds). Later turns may have none: after a
    # tool result gpt-oss often acts without thinking again (pilot: about a third of later turns),
    # and the student learns those turns with an empty think block.
    require_reasoning: bool = True
    # The student's training length (configs/sft.toml max_length): longer traces are skipped
    # in training, so generation stops and rejects them (`too_long`) as soon as they pass it.
    max_sample_tokens: int | None = 8192
    # gpt-oss puts Markdown tables into some final reports despite the style notes (2 of 10
    # pilot-6 traces, each about 13 minutes of teacher time). It is asked once to rewrite that
    # reply as a list before the trace is rejected as `markdown_table`.
    rewrite_tables: bool = True
    # Extra draws of a final reply that would leave only a plan (see `stops_at_plan`).
    plan_only_resamples: int = 2


TABLE_REWRITE = (
    "Rewrite your last reply to the user with the same content but no Markdown table: turn each "
    "table into a short bullet list. Reply with the rewritten text only."
)


# Classes where answering without any tool is the right behaviour.
DIRECT_CLASSES = frozenset({"quick_answer"})
# Classes where a plan plus questions can be the whole right answer.
PLAN_ANSWER_CLASSES = frozenset({"quick_answer", "clarify"})
# Questions to the user are not work: pilot 12's judge failed traces that asked and stopped
# without starting what did not depend on the answer.
WORK_TOOLS = frozenset({"spawn_agent", "delegate_chunks", "web_search", "web_fetch"})
RESAMPLE_SEED_STEP = 104_729
FORCE_WORK_TURNS = 3  # turns on which a tool call is required until work starts


def stops_at_plan(stored: list[dict], task_class: str) -> bool:
    """Whether ending the trace now would leave only a plan (and perhaps questions): no
    subagent or search yet. The pilots' commonest Emperor failure (4 of 10 in pilot 10)."""
    if task_class in PLAN_ANSWER_CLASSES:
        return False
    names = {
        call["function"]["name"]
        for message in stored
        if message["role"] == "assistant"
        for call in message.get("tool_calls") or []
    }
    return bool(names) and not names & WORK_TOOLS


ATTEMPT_SEED_STEP = 1_000_003
ROUND_SEED_STEP = 7_000_001
SEED_MASK = 0x7FFFFFFF


def teacher_system(context_tokens: int) -> str:
    """What the teacher is told: the real prompt, the artefact shapes and the style, with the
    context-budget line last. Everything before it is the same for every task, so the teacher
    server reuses its cached prefix instead of reprocessing about 2,000 tokens per task."""
    shapes = "\n\n".join(prompt(name).strip() for name in ("plan", "questions", "brief"))
    budget = system_prompt(context_tokens).rstrip().rsplit("\n", 1)[1]
    return f"{prompt('emperor-root').rstrip()}\n\n{shapes}\n\n{STYLE}\n{budget}\n"


_ENV_SYSTEM = """\
You simulate the tool results of an agent platform, for training data. You are not the
assistant and never address the user. You receive the user's task and one tool call the
assistant made, and you reply with the tool's result only: plain text, no commentary, no JSON
wrapper unless the tool would return one.

Rules:
- web_search: return 4 to 6 results, each as a title, a plausible https URL and a one-line
  snippet, one per line. Content must be realistic and consistent with what is known.
- web_fetch: return the readable text of the page, 120 to 280 words, with concrete facts.
- A subagent report (await_tasks): write the report the subagent would send for its brief,
  following the brief's "Output format", 40 to 120 words (30 to 70 words each when more than
  four reports are asked for at once, as for chunks of one long input), with concrete
  evidence for each acceptance check. Occasionally (about one time in six) report a genuine
  problem or a failed check, so the assistant has to re-plan.
- ask_user: write the user's answers, one line per question, as a normal person would; accept
  the recommended answer about half the time.
Never include credentials, API keys, tokens or private endpoints in any result.
"""


ENV_HISTORY_RESULTS = 6  # earlier results the simulator sees, newest last
ENV_HISTORY_CHARS = 1200  # of each
# The batched await's reply budget. The two role slots share one KV buffer (24,576 tokens): the
# teacher's slot holds up to about 14,600 (a 10,500-token prompt plus a 4,096-token reply). With
# 8,192 here the simulator's slot reached 11,900 in a direct test, the server ran out of KV
# space and purged the teacher's cached prompt (no error, but about 100 s of re-prefill on the
# teacher's next turn). Reports are 60-180 words each; any the batch leaves out is written alone.
BATCH_REPORT_TOKENS = 4096


class Environment:
    """Simulates tool results; ids and bookkeeping are deterministic, content comes from the LLM."""

    def __init__(self, client: Chat, task_text: str, seed: int, max_tokens: int = 1200):
        self.client = client
        self.task_text = task_text
        self.seed = seed
        self.max_tokens = max_tokens
        self.next_task = 1
        self.pending: dict[str, str] = {}  # task id -> brief
        self.calls = 0
        self.history: list[str] = []  # earlier simulated results in this task

    def _ask(self, request: str, max_tokens: int | None = None) -> str:
        """One simulated result, consistent with the ones already given in this task: written
        independently, pages and reports contradicted each other (one pilot trace was failed for
        not noticing three different issue counts for the same project)."""
        self.calls += 1
        if self.history:
            earlier = "\n\n".join(self.history[-ENV_HISTORY_RESULTS:])
            request = (
                f"Results already given in this session (stay consistent with every fact in "
                f"them):\n{earlier}\n\n{request}"
            )
        reply = self.client.chat(
            [
                {"role": "system", "content": _ENV_SYSTEM},
                {"role": "user", "content": request},
            ],
            temperature=0.8,
            seed=self.seed + self.calls,
            max_tokens=max_tokens or self.max_tokens,
        )
        text = (reply.get("content") or "").strip() or "(no output)"
        self.history.append(text[:ENV_HISTORY_CHARS])
        return text

    def run(self, name: str, arguments: dict) -> str:
        if name == "update_plan":
            return json.dumps({"ok": True, "steps": len(arguments.get("steps", []))})
        if name in ("spawn_agent", "delegate_chunks"):
            return self._spawn(name, arguments)
        if name == "await_tasks":
            return self._await(arguments)
        if name == "ask_user":
            questions = [q["question"] for q in arguments["questions"]]
            answers = self._ask(
                f"User task: {self.task_text}\n\nTool: ask_user\nQuestions:\n"
                + "\n".join(f"{i + 1}. {q}" for i, q in enumerate(questions))
                + "\n\nReturn the answers, one per line."
            )
            return json.dumps({"answers": answers})
        if name in ("web_search", "web_fetch"):
            return self._ask(
                f"User task: {self.task_text}\n\nTool: {name}\nArguments: "
                f"{json.dumps(arguments, ensure_ascii=False)}"
            )
        return json.dumps({"error": f"unknown tool {name}"})

    def _spawn(self, name: str, arguments: dict) -> str:
        if name == "delegate_chunks":
            tokens = max(int(arguments.get("chunk_tokens", 32000)), 1)
            count = max(2, 300_000 // tokens)
            ids = []
            for _ in range(min(count, 12)):
                task_id = f"t{self.next_task}"
                self.next_task += 1
                self.pending[task_id] = arguments["brief"]
                ids.append(task_id)
            if arguments.get("reduce"):
                task_id = f"t{self.next_task}"
                self.next_task += 1
                self.pending[task_id] = "Merge the chunk reports: " + arguments["reduce"]
                ids.append(task_id)
            return json.dumps({"task_ids": ids})
        task_id = f"t{self.next_task}"
        self.next_task += 1
        self.pending[task_id] = arguments["brief"]
        return json.dumps({"task_id": task_id, "status": "running"})

    def _await(self, arguments: dict) -> str:
        wanted = arguments.get("task_ids") or list(self.pending)
        known = {t: self.pending.pop(t) for t in wanted if t in self.pending}
        written = self._batch_reports(known) if len(known) > 1 else {}
        reports = []
        for task_id in wanted:
            brief = known.get(task_id)
            if brief is None:
                reports.append({"task_id": task_id, "status": "unknown_task"})
                continue
            text = written.get(task_id) or self._ask(
                f"User task: {self.task_text}\n\nTool: await_tasks, subagent {task_id}\n"
                f"The subagent's brief was:\n{brief}\n\nWrite its report."
            )
            reports.append({"task_id": task_id, "status": "done", "report": text})
        if not reports:
            return json.dumps({"reports": [], "note": "no running tasks"})
        return json.dumps({"reports": reports}, ensure_ascii=False)

    def _batch_reports(self, briefs: dict[str, str]) -> dict[str, str]:
        """All awaited reports from one simulator call (a chunked job awaits up to 13 at once,
        which took one call each); any report it does not deliver is written on its own."""
        parts = "\n\n".join(
            f"Subagent {task_id}. Its brief was:\n{brief}" for task_id, brief in briefs.items()
        )
        text = self._ask(
            f"User task: {self.task_text}\n\nTool: await_tasks, {len(briefs)} subagents.\n\n"
            f"{parts}\n\nWrite each subagent's report, in this order. Start each one with a line "
            "holding only `### <subagent id>` (for example `### t1`), then the report.",
            max_tokens=min(BATCH_REPORT_TOKENS, self.max_tokens * len(briefs)),
        )
        return split_reports(text, list(briefs))


def split_reports(text: str, task_ids: list[str]) -> dict[str, str]:
    """Each report under its `### <id>` line. Only a line naming a known id starts a report, so
    a report's own `### Findings` heading stays part of it."""
    names = "|".join(re.escape(t) for t in sorted(task_ids, key=len, reverse=True))
    header = re.compile(rf"(?m)^###[ \t]*[`*]*({names})[`*:]*[ \t]*$")
    marks = list(header.finditer(text))
    found: dict[str, str] = {}
    for mark, following in zip(marks, [*marks[1:], None], strict=False):
        body = text[mark.end() : following.start() if following else len(text)].strip()
        if body and mark.group(1) not in found:
            found[mark.group(1)] = body
    return found


def _normalise_calls(raw_calls: list[dict], counter: list[int]) -> list[dict]:
    calls = []
    for raw in raw_calls:
        function = raw.get("function") or {}
        arguments = function.get("arguments", "")
        if not isinstance(arguments, str):
            arguments = json.dumps(arguments, ensure_ascii=False)
        counter[0] += 1
        calls.append(
            {
                "id": f"call_{counter[0]}",
                "type": "function",
                "function": {"name": function.get("name", ""), "arguments": arguments},
            }
        )
    return calls


# The field llama-server reads an assistant turn's reasoning from (it renders it into gpt-oss's
# analysis channel), so the teacher keeps its reasoning across the tool calls of one task.
TEACHER_REASONING_FIELD = "reasoning_content"


# Fields Emperor's prompt requires but the tool schemas leave optional. The teacher ignored the
# instruction to set them (spawn_agent without tags in 4 of 7 pilot-9 traces; plan steps without
# acceptance checks), so the teacher's copy of the schemas marks them required. The stored sample
# and the student keep the real schemas.
TEACHER_REQUIRED = {"spawn_agent": ("tier", "tags")}
TEACHER_REQUIRED_STEP = ("owner", "acceptance")


def teacher_tools(names: list[str]) -> list[dict]:
    tools = copy.deepcopy(openai_tools(names))
    for tool in tools:
        function = tool["function"]
        parameters = function["parameters"]
        extra = TEACHER_REQUIRED.get(function["name"], ())
        parameters["required"] = [*parameters.get("required", []), *extra]
        if function["name"] == "update_plan":
            step = parameters["properties"]["steps"]["items"]
            step["required"] = [*step.get("required", []), *TEACHER_REQUIRED_STEP]
    return tools


def sample_tokens(messages: list[dict], tools: list[dict]) -> int:
    """About how many tokens the student sees for this sample: messages, reasoning and tool
    definitions at four characters a token (within 10% of the Qwen3.5 tokenizer in the pilot)."""
    return estimate_tokens(json.dumps(messages, ensure_ascii=False)) + estimate_tokens(
        json.dumps(tools, ensure_ascii=False)
    )


def reasoning_of(reply: dict) -> str:
    reasoning = reply.get("reasoning_content")
    return reasoning.strip() if isinstance(reasoning, str) else ""


def with_reasoning(message: dict, reasoning: str, field: str = "reasoning_content") -> dict:
    """The message plus the teacher's reasoning for it, under `field` (unchanged when empty)."""
    return {**message, field: reasoning} if reasoning else message


_PREFLIGHT_USER = (
    "Plan the release of version 2.0 of a small command-line tool: record a three-step plan "
    "with update_plan."
)


def check_teacher_reasoning(teacher: Chat, config: "GenerationConfig") -> None:
    """Fail fast when the teacher does not return its reasoning, both as generation calls it on
    the first turn (`tool_choice=required`) and without forcing a tool. Raises
    TeacherSetupError; TeacherError when the server cannot be reached."""
    messages = [
        {"role": "system", "content": teacher_system(65536)},
        {"role": "user", "content": _PREFLIGHT_USER},
    ]
    tools = teacher_tools(["update_plan"])
    modes = [("tool_choice=required", {"tool_choice": "required"}), ("no forced tool", {})]
    if not config.force_first_tool:
        modes = modes[1:]
    for label, extra in modes:
        reply: dict = {}
        for seed in range(3):  # an unparsable reply is one bad sample, not a broken setup
            try:
                reply = teacher.chat(
                    messages,
                    tools=tools,
                    temperature=config.temperature,
                    seed=seed,
                    max_tokens=config.max_tokens,
                    **extra,
                )
                break
            except TeacherOutputError:
                continue
        if not reasoning_of(reply):
            raise TeacherSetupError(
                f"the teacher returned no reasoning_content ({label}); a thinking student "
                "cannot be trained on its traces. Local: check that llama-server runs with "
                "--jinja and extracts reasoning (not --reasoning-format none) and that the "
                "reasoning effort is set. Hosted: check that the teacher role enables thinking"
            )


def generate_trace(
    record: PromptRecord,
    teacher: Chat,
    environment_client: Chat,
    config: GenerationConfig | None = None,
    *,
    attempt: int = 0,
) -> tuple[dict | None, str | None]:
    """Play one prompt to the end; returns (sample, None) or (None, rejection reason).

    `attempt` shifts every seed, so a retry of the same prompt takes a different path.
    """
    config = config or GenerationConfig()
    base_seed = (record.seed + attempt * ATTEMPT_SEED_STEP) & SEED_MASK
    requires_tools = record.task_class not in config.direct_classes
    context_tokens = record.context_budget_k * 1024
    tools = openai_tools(record.tools)
    env = Environment(environment_client, record.text, base_seed)
    teacher_messages = [
        {"role": "system", "content": teacher_system(context_tokens)},
        {"role": "user", "content": record.text},
    ]
    stored = [
        {"role": "system", "content": system_prompt(context_tokens)},
        {"role": "user", "content": record.text},
    ]
    counter = [0]
    for turn in range(config.max_turns):
        # A tool call is required on the first turn, and on the next ones while nothing but a
        # plan (or a question) exists: in pilots 10-13 the teacher kept replying with the plan
        # and questions even when every reply was drawn three times.
        force = (
            requires_tools
            and config.force_first_tool
            and (
                turn == 0 or (turn < FORCE_WORK_TURNS and stops_at_plan(stored, record.task_class))
            )
        )
        extra = {"tool_choice": "required"} if force else {}
        for resample in range(config.plan_only_resamples + 1):
            reply = teacher.chat(
                teacher_messages,
                tools=teacher_tools(record.tools),
                temperature=config.temperature,
                seed=(base_seed + turn + resample * RESAMPLE_SEED_STEP) & SEED_MASK,
                max_tokens=config.max_tokens,
                **extra,
            )
            # A reply that ends the task while the only thing done is a plan is drawn again
            # (another seed); the stored trace keeps only the turn that was used.
            if reply.get("tool_calls") or not stops_at_plan(stored, record.task_class):
                break
        content = (reply.get("content") or "").strip()
        calls = _normalise_calls(reply.get("tool_calls") or [], counter)
        if not calls and not content:
            return None, "empty_reply"
        # Still only a plan after every draw: the judge failed each such trace in pilots 10-14
        # (it asks or restates and does nothing), so it is rejected here, before judge time.
        if not calls and stops_at_plan(stored, record.task_class):
            return None, "plan_only"
        reasoning = reasoning_of(reply)
        if config.require_reasoning and turn == 0 and not reasoning:
            return None, "no_reasoning"
        message: dict = {"role": "assistant", "content": content}
        if calls:
            message["tool_calls"] = calls
        # The teacher keeps its own reasoning for this task's earlier turns, as gpt-oss expects
        # across tool calls and as the student will see it; the stored sample keeps it too.
        # The field is sent even when empty: DeepSeek's thinking mode rejects a tool-calling
        # request whose earlier assistant turns lack `reasoning_content` (HTTP 400, pilot 1).
        teacher_messages.append({**message, TEACHER_REASONING_FIELD: reasoning})
        stored.append(with_reasoning(message, reasoning))
        if not calls:
            break
        for call in calls:
            name = call["function"]["name"]
            arguments, errors = check_call(name, call["function"]["arguments"], record.tools)
            if errors or arguments is None:
                return None, "tool_call_invalid"
            result = env.run(name, arguments)
            tool_message = {"role": "tool", "tool_call_id": call["id"], "content": result}
            teacher_messages.append(tool_message)
            stored.append(tool_message)
        if config.max_sample_tokens and sample_tokens(stored, tools) > config.max_sample_tokens:
            return None, "too_long"  # training would drop it; stop paying the teacher for it
    else:
        return None, "turn_limit"
    if config.max_sample_tokens and sample_tokens(stored, tools) > config.max_sample_tokens:
        return None, "too_long"

    if requires_tools and not any(m.get("tool_calls") for m in stored[2:]):
        return None, "no_tool_use"
    if (
        config.rewrite_tables
        and table_rows(stored[-1].get("content") or "") > MAX_TABLE_ROWS
        and table_rows("\n".join(m.get("content") or "" for m in stored[2:-1])) <= MAX_TABLE_ROWS
    ):
        # The teacher rewrites its own final reply once; the trace is not thrown away for it.
        rewrite = teacher.chat(
            [*teacher_messages, {"role": "user", "content": TABLE_REWRITE}],
            temperature=config.temperature,
            seed=(base_seed + config.max_turns) & SEED_MASK,
            max_tokens=config.max_tokens,
        )
        content = (rewrite.get("content") or "").strip()
        if content:
            # The stored turn takes the rewrite's reasoning too: the original reasoning led to the
            # table, so keeping it would pair one answer with another answer's thinking.
            final = {k: v for k, v in stored[-1].items() if k != "reasoning_content"}
            stored[-1] = with_reasoning({**final, "content": content}, reasoning_of(rewrite))
    if table_rows("\n".join(m.get("content") or "" for m in stored[2:])) > MAX_TABLE_ROWS:
        return None, "markdown_table"

    sample = {
        "id": record.id,
        "task_class": record.task_class,
        "specificity": record.specificity,
        "context_budget_k": record.context_budget_k,
        "tools": record.tools,
        "messages": stored,
        "meta": {
            "teacher": config.teacher_model,
            "licence": config.licence,
            "seed": base_seed,
            "host": config.host,
            "attempt": config.attempt,
            **config.provenance,  # a hosted run's commit, config, models, guidance and pilot
        },
    }
    check = validate_sample(sample)
    if not check.ok:
        return None, check.reasons[0]
    return sample, None


def _sample_with_retries(
    record: PromptRecord, teacher: Chat, env_client: Chat, config: GenerationConfig
) -> tuple[dict | None, str | None, list[str]]:
    """Try the prompt up to `1 + retries` times; returns (sample, last reason, failed reasons)."""
    failures: list[str] = []
    reason: str | None = None
    for attempt in range(config.retries + 1):
        try:
            sample, reason = generate_trace(record, teacher, env_client, config, attempt=attempt)
        except TeacherContextError:  # the trace outgrew the server's context or KV cache
            sample, reason = None, "context_exceeded"
        except TeacherOutputError as error:
            sample, reason = None, "teacher_output_unparsable"
            # What the server said, for diagnosis (a hosted 400 names the bad field).
            log.warning("%s: teacher output rejected: %s", record.id, str(error)[:300])
        except TeacherError:
            raise
        except Exception as error:  # one bad sample must not end an overnight run
            sample, reason = None, f"error:{type(error).__name__}"
        if sample:
            return sample, None, failures
        failures.append(reason or "unknown")
        if reason in config.no_retry_reasons:
            break
    return None, reason, failures


def run_generation(
    prompts_path: Path,
    out_dir: Path,
    teacher: Chat,
    environment_client: Chat | None = None,
    *,
    config: GenerationConfig | None = None,
    limit: int | None = None,
    should_stop: Callable[[], bool] = lambda: False,
    log: Callable[[str], None] = lambda _: None,
    workers: int = 1,
) -> dict:
    """Generate traces for every prompt not yet done; resumable and safe to stop between samples.
    `workers` prompts run at once (hosted APIs; a local llama-server takes one at a time).

    Accepted samples go to `out_dir/traces`, rejections (with reasons) to `out_dir/rejects`; both
    count as done. Returns counts and whether the run stopped early.
    """
    config = config or GenerationConfig()
    traces = ShardWriter(out_dir / "traces", "traces")
    rejects = ShardWriter(out_dir / "rejects", "rejects")
    # The latest record per id counts, and an excluded pilot's tasks are done again.
    finished = set(current(out_dir / "traces")) | set(current(out_dir / "rejects"))
    todo = [PromptRecord(**r) for r in read_jsonl(prompts_path) if r["id"] not in finished]
    if limit is not None:
        todo = todo[:limit]
    counts = {"todo": len(todo), "accepted": 0, "rejected": 0, "stopped": False}
    env_client = environment_client or teacher
    if todo and config.require_reasoning:
        try:
            check_teacher_reasoning(teacher, config)
        except TeacherError as error:
            return {**counts, "stopped": True, "error": str(error)}

    def work(record: PromptRecord):
        return _sample_with_retries(record, teacher, env_client, config)

    def handle(record: PromptRecord, result) -> None:
        sample, reason, failures = result
        if sample:
            sample["meta"]["attempts"] = len(failures) + 1
            if failures:
                sample["meta"]["attempt_failures"] = failures
            traces.write(sample)
            counts["accepted"] += 1
        else:
            rejects.write(
                {
                    "id": record.id,
                    "task_class": record.task_class,
                    "reason": reason,
                    "attempts": len(failures),
                    "attempt_failures": failures,
                    **config.provenance,
                }
            )
            counts["rejected"] += 1
        log(f"{record.id} {'ok' if sample else reason}")

    # A TeacherError (server gone, budget reached) leaves the remaining ids undone for a resume.
    outcome = run_items(todo, work, handle, workers=workers, should_stop=should_stop)
    counts["stopped"] = outcome["stopped"]
    if "error" in outcome:
        counts["error"] = outcome["error"]
    return counts
